export function getWorkEnrichedDetails(work) {
  const curated = CURATED_WORK_METADATA[work.id];
  if (curated) {
    return {
      tags: curated.tags,
      sentences: curated.sentences,
      descriptionFull: curated.sentences.join(" "),
      metaDescription: curated.sentences.slice(0, 2).join(" "),
    };
  }

  const text = `${work.title} ${work.description || ""} ${work.credit || ""}`.toLowerCase();
  const tags = new Set();

  if (/three(\.js)?|3d|orbit|scene|glsl/.test(text)) {
    tags.add("#ThreeJS");
    tags.add("#WebGL");
  } else if (/webgl|shader|rasterizer/.test(text)) {
    tags.add("#WebGL");
  }

  if (/canvas|2d|pixel|arcade|tetris/.test(text)) {
    tags.add("#Canvas");
  }

  if (/audio|sound|music|synthesizer|beat/.test(text)) {
    tags.add("#WebAudio");
    tags.add("#AudioAPI");
  }

  if (/gpt|openai|claude|ai|gemini|llm|deepseek/.test(text)) {
    tags.add("#AIWebApps");
  }

  if (work.category === "game") {
    tags.add("#HTML5Game");
    tags.add("#GameDev");
  } else if (work.category === "visual") {
    tags.add("#GenerativeArt");
    tags.add("#Canvas");
  } else {
    tags.add("#WebTool");
    tags.add("#Productivity");
  }

  tags.add("#HTML5");
  tags.add("#SingleFileHTML");

  if (!tags.has("#ThreeJS") && !tags.has("#Canvas") && !tags.has("#WebGL")) {
    tags.add("#Canvas");
  }

  const categoryLabel =
    work.category === "game"
      ? "HTML5 game"
      : work.category === "visual"
        ? "interactive visual experiment"
        : "lightweight web tool";

  const cleanDesc = (work.description || "").trim().replace(/\.+$/, "");
  const sentences = [
    `${work.title} is an engaging single-file ${categoryLabel} created by ${work.credit || "an independent developer"}.`,
    cleanDesc ? `${cleanDesc}.` : "It delivers a self-contained, responsive browser experience with smooth performance.",
    "The application is built entirely in a single portable HTML file, executing client-side with zero external builds, compilers, or server dependencies.",
    "Running securely inside OneHTML's isolated zero-trust sandbox, it enforces strict Content Security Policies and zero third-party tracking.",
    `Launch ${work.title} instantly in your web browser, explore interactive controls, and share this single-file creation with the web community.`,
  ];

  return {
    tags: Array.from(tags),
    sentences,
    descriptionFull: sentences.join(" "),
    metaDescription: sentences.slice(0, 2).join(" "),
  };
}
